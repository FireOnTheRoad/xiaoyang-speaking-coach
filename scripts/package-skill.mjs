#!/usr/bin/env node
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const skillDir = join(root, 'skills', 'bilingual-speaking-practice')
const appDir = join(skillDir, 'assets', 'app')
const files = [
  'package.json',
  'package-lock.json',
  'index.html',
  'vite.config.ts',
  'tsconfig.json',
  'tsconfig.app.json',
  'tsconfig.node.json',
  'README.md',
]

rmSync(appDir, { recursive: true, force: true })
mkdirSync(appDir, { recursive: true })
for (const file of files) {
  const source = join(root, file)
  if (!existsSync(source)) throw new Error(`Missing required app file: ${file}`)
  cpSync(source, join(appDir, file))
}
cpSync(join(root, 'src'), join(appDir, 'src'), { recursive: true })
mkdirSync(join(appDir, 'scripts'), { recursive: true })
cpSync(join(root, 'scripts', 'transcribe.py'), join(appDir, 'scripts', 'transcribe.py'))
writeFileSync(
  join(appDir, 'PACKAGE_INFO.md'),
  `# Bundled app\n\nThis directory is generated by \`npm run package:skill\` from the repository root. Do not edit it directly; edit the root app and regenerate the skill package.\n`,
  'utf8',
)
console.log(`Packaged app into ${appDir}`)
